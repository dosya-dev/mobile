export type IconName = keyof typeof ICONS;

/**
 * Names that point somewhere and so mirror in a right-to-left layout. One list:
 * the test helper `unflippedIcons` reads it too. Media names (play-skip-*),
 * swap-horizontal, open/share, check marks and clocks never flip.
 */
export const DIRECTIONAL_ICONS: ReadonlySet<IconName> = new Set<IconName>([
  "chevron-back",
  "chevron-forward",
  "arrow-forward-outline",
  "arrow-undo",
  "arrow-undo-outline",
  "log-out-outline",
  "send-outline",
]);

type LucideProps = ComponentProps<typeof Activity>;

export interface IconProps extends Omit<LucideProps, "name"> {
  name: IconName;
  size?: number;
  color?: string;
  /** `false` keeps a directional icon unflipped in RTL (media transport, timelines). */
  mirror?: boolean;
}

/**
 * `size` and `color` are passed through rather than defaulted here: every call
 * site already sets them from the theme, and a default would quietly win
 * wherever one was forgotten instead of showing up in review.
 */
export function Icon({ name, mirror, style, ...rest }: IconProps) {
  const Glyph = ICONS[name];
  if (mirror !== false && DIRECTIONAL_ICONS.has(name) && layoutIsRtl()) {
    // The flip goes on a wrapping View, never on the Svg: react-native-svg also
    // applies a style transform inside the drawing, around its top-left corner,
    // which moves the glyph out of its own box and leaves an empty square (seen
    // on the simulator). Caller style first, the flip last. The direction cannot
    // change without a reload.
    return (
      // rtl-ok: mirrored
      <View style={[style as StyleProp<ViewStyle>, { transform: [{ scaleX: -1 }] }]}>
        <Glyph {...rest} />
      </View>
    );
  }
  // Left to right: exactly the props the caller gave.
  return <Glyph {...rest} {...(style === undefined ? null : { style })} />;
}
