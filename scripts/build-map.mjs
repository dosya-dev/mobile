import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

/**
 * Inlines maplibre into a single self-contained HTML string for the map
 * WebView, exactly as scripts/build-reader.mjs does for foliate-js.
 *
 * maplibre-gl and pmtiles are devDependencies on purpose: they run inside the
 * WebView, never in the React Native JS context, so they must not reach the
 * app bundle.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const result = await build({
  entryPoints: [join(root, "src/map/map-page/main.js")],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  write: false,
  // maplibre ships a worker it loads via `new Worker(new URL(...))`. esbuild
  // inlines it as a blob when bundling for the browser, which is what we want -
  // a single string with no external requests.
  platform: "browser",
});

const js = result.outputFiles[0]?.text ?? "";
// maplibre's stylesheet is read straight from the package rather than imported:
// an import would need a CSS loader whose output esbuild then emits as a second
// file, which is the opposite of the single self-contained string we want.
const css = readFileSync(join(root, "node_modules/maplibre-gl/dist/maplibre-gl.css"), "utf8");

if (!js || js.trim().length === 0) {
  console.error("build-map: esbuild produced an empty bundle - refusing to write a stub MAP_HTML.");
  process.exit(1);
}

const template = readFileSync(join(root, "src/map/map-page/index.html"), "utf8");
const injection =
  (css ? `<style>${css.replace(/<\/style>/gi, "<\\/style>")}</style>` : "") +
  `<script>${js.replace(/<\/script>/gi, "<\\/script>")}</script>`;
const html = template.replace("<!--INJECT:BUNDLE-->", () => injection);

// replace() silently returns the input unchanged when the marker is missing,
// which would write a "successful" MAP_HTML with no map in it. Fail instead.
if (html === template || html.includes("<!--INJECT:BUNDLE-->") || !html.includes("<script>")) {
  console.error("build-map: failed to inject the bundle - <!--INJECT:BUNDLE--> marker not found/replaced.");
  process.exit(1);
}

const out = `// GENERATED by scripts/build-map.mjs - do not edit. Rebuild: npm run build:map
// eslint-disable
export const MAP_HTML = ${JSON.stringify(html)};
`;
writeFileSync(join(root, "src/map/mapHtml.generated.ts"), out);
console.log(`mapHtml.generated.ts written (${(html.length / 1024).toFixed(0)} KB)`);
