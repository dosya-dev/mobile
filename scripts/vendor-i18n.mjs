#!/usr/bin/env node
// Vendor the i18n runtime and the reviewed catalogs into apps/mobile so the app
// is fully self-contained.
//
// WHY: same reason vendor-e2ee.mjs exists. apps/mobile is not mirrored like
// web, but it installs standalone with its own lockfile (EAS builds it from
// apps/mobile), so every monorepo package it uses is vendored and nothing
// reaches for ../../packages or ../desktop at build time. Edit the runtime in
// apps/desktop/src/i18n, the catalogs in packages/i18n/mobile, then re-run this.
//
// Two things are vendored:
//   1. The ICU runtime (icu.ts, translator.ts, match.ts) from
//      apps/desktop/src/i18n, copied FLAT and unchanged so its relative
//      imports (./icu.ts, ./keys.ts, ./locales.ts, ./external-keys.ts) keep
//      working (tsconfig allowImportingTsExtensions).
//   2. The catalogs from packages/i18n/mobile: en.catalog.json becomes
//      messages/en.json ({key: source}), each SHIPPED language becomes
//      messages/<lang>.json. From them the script generates keys.ts
//      (MessageKey), locales.ts, loaders.ts and shipped.json.
//
// SHIPPED is computed, not hand-listed. A language ships when (1) it is not
// an unsupported right-to-left language (ur), (2) it has every catalog key
// that is not `translate: false`, and (3) every message parses, has the same
// argument names as the English and uses only plural branches the language
// has (Intl.PluralRules, plus other and =N). A language that was shipped
// before and would drop out fails the run unless named with --allow-drop.
// A language file with a key the catalog lacks fails the whole run.
//
// MONOREPO-ONLY step. Re-run (`npm run vendor:i18n`) whenever the catalogs or
// the desktop runtime change, then commit src/i18n/.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

