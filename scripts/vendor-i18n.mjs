  tr: 'Türkçe',
  de: 'Deutsch',
  fr: 'Français',
  'fr-CA': 'Français (Canada)',
  es: 'Español',
  'es-419': 'Español (Latinoamérica)',
  it: 'Italiano',
  pl: 'Polski',
  'pt-BR': 'Português (Brasil)',
  'pt-PT': 'Português (Portugal)',
  nl: 'Nederlands',
  sv: 'Svenska',
  da: 'Dansk',
  nb: 'Norsk bokmål',
  fi: 'Suomi',
  cs: 'Čeština',
  ro: 'Română',
  hu: 'Magyar',
  el: 'Ελληνικά',
  id: 'Bahasa Indonesia',
  vi: 'Tiếng Việt',
  bg: 'Български',
  sk: 'Slovenčina',
  et: 'Eesti',
  'zh-Hans': '简体中文',
  'zh-Hant': '繁體中文',
  sl: 'Slovenščina',
  th: 'ไทย',
  hr: 'Hrvatski',
