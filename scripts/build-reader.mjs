import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const result = await build({
  entryPoints: [join(root, "src/reader/reader-page/main.js")],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  write: false,
  // PDF support (vendor/foliate-js/pdf.js -> vendor/pdfjs/pdf.mjs) is
  // deliberately not vendored: it needs ~13MB of fonts/cmaps and a Worker
  // script loaded via a real URL, and does a top-level `fetch()` for CSS -
  // none of which works from a single self-contained inlined-HTML string
  // with no network access. Mark it external so esbuild doesn't try to
  // resolve `./vendor/pdfjs/pdf.mjs` (which isn't there) and fails the
  // build. See vendor/foliate-js/VENDORED.md. The other dynamic format
  // loaders view.js imports (epub/mobi/fb2/comic-book, plus their
  // vendor/zip.js and vendor/fflate.js deps) are vendored and get inlined
  // normally.
  external: ["./pdf.js"],
});
const js = result.outputFiles[0].text;
if (!js || js.trim().length === 0) {
  console.error("build-reader: esbuild produced an empty bundle - refusing to write a stub READER_HTML.");
  process.exit(1);
}
const template = readFileSync(join(root, "src/reader/reader-page/index.html"), "utf8");
const html = template.replace("<!--INJECT:BUNDLE-->", () => `<script>${js.replace(/<\/script>/gi, "<\\/script>")}</script>`);

// String.prototype.replace() silently returns the input unchanged when the
// pattern isn't found (e.g. the marker was typo'd or removed from
// index.html), which would otherwise write out a "successful" READER_HTML
// with no reader code in it at all. Fail hard instead of shipping that.
if (html === template || html.includes("<!--INJECT:BUNDLE-->") || !html.includes("<script>")) {
  console.error("build-reader: failed to inject the bundle into index.html - <!--INJECT:BUNDLE--> marker not found/replaced.");
  process.exit(1);
}

const out = `// GENERATED by scripts/build-reader.mjs - do not edit. Rebuild: npm run build:reader
// eslint-disable
export const READER_HTML = ${JSON.stringify(html)};
`;
writeFileSync(join(root, "src/reader/readerHtml.generated.ts"), out);
console.log(`readerHtml.generated.ts written (${(html.length / 1024).toFixed(0)} KB)`);
